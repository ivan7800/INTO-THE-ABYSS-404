import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const nodes={},saved=new Map();
const canvasContext=new Proxy({createLinearGradient:()=>({addColorStop(){}}),createRadialGradient:()=>({addColorStop(){}})},{get:(o,k)=>o[k]??(()=>{})});
const el=id=>nodes[id]??={textContent:'',hidden:false,disabled:false,value:'',style:{},dataset:{},addEventListener(){},setAttribute(){},getBoundingClientRect(){return {left:0,top:0,width:640,height:640}},replaceChildren(){},getContext(){return canvasContext}};
const env={document:{querySelector:el,querySelectorAll:()=>[],createElement:()=>({click(){}}),addEventListener(){},hidden:false},window:{matchMedia:()=>({matches:false})},localStorage:{setItem:(k,v)=>saved.set(k,v),getItem:k=>saved.get(k)??null},performance:{now:()=>1000},requestAnimationFrame:()=>1,console};
vm.createContext(env);vm.runInContext(fs.readFileSync(new URL('./game.js',import.meta.url),'utf8'),env);
const run=s=>vm.runInContext(s,env);
run('campaign.sector=2;init();state.turn=2;freezeIntent()');
assert.equal(run('state.resonance!==null'),true,'resonance should be announced');
const tile=run('JSON.stringify(state.resonance)');
run('state.units.find(u=>u.id===1).x=6;state.units.find(u=>u.id===1).y=1');
assert.equal(run('JSON.stringify(state.resonance)'),tile,'changing position cannot retarget warning');
const initial=run('state.corruption');
run('state.intent=[];state.omen=null;state.rifts=[{x:state.resonance.x,y:state.resonance.y}];resolveResonance()');
assert.equal(run('state.corruption'),initial+4,'resonance adds four corruption');
run('campaign.sector=2;init();state.turn=2;freezeIntent()');
assert.equal(run('state.resonance!==null'),true);
run('state.intent=[];state.omen=null;state.units.find(u=>u.id===state.resonance.source).hp=0;var before=state.corruption;resolveResonance();if(state.corruption!==before)throw Error("dead source still pulses")');
run('campaign.sector=2;init();state.turn=2;freezeIntent()');
run('state.intent=[];state.omen=null;state.rifts=state.rifts.filter(r=>!(r.x===state.resonance.x&&r.y===state.resonance.y));var before=state.corruption;resolveResonance();if(state.corruption!==before)throw Error("sealed rift still pulses")');
run('campaign.sector=2;init();state.turn=2;freezeIntent();persist()');
const remembered=run('JSON.stringify(state.resonance)');
assert.equal(run('restore()'),true);
assert.equal(run('JSON.stringify(state.resonance)'),remembered,'resonance save must restore unchanged');
console.log('PASS phase16: fixed telegraph, pulse, dead-source counterplay, sealed-rift counterplay, restore');
