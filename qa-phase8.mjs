import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const events={},nodes={},saved=new Map();
const context2d=new Proxy({createLinearGradient:()=>({addColorStop(){}}),createRadialGradient:()=>({addColorStop(){}})}, {get:(o,k)=>o[k]??(()=>{})});
function el(id){return nodes[id]??={textContent:'',hidden:false,disabled:false,value:'',addEventListener(name,fn){events[id+':'+name]=fn},getBoundingClientRect(){return {left:0,top:0,width:640,height:640}},replaceChildren(){},getContext(){return context2d}}}
const env={document:{querySelector:el,createElement:()=>({}),addEventListener(){},hidden:false},window:{matchMedia:()=>({matches:false})},localStorage:{setItem:(k,v)=>saved.set(k,v),getItem:k=>saved.get(k)??null},performance:{now:()=>1000},requestAnimationFrame:()=>1,console};
vm.createContext(env);vm.runInContext(fs.readFileSync(new URL('./game.js',import.meta.url),'utf8'),env);
const run=s=>vm.runInContext(s,env);
assert.equal(run('state.omen'),null,'no omen first turn');
assert.equal(run('state.intent.length'),3);
const frozen=run('JSON.stringify(state.intent)');
run('state.units.find(u=>u.id===1).x=4');
assert.equal(run('JSON.stringify(state.intent)'),frozen,'enemy cannot retarget after movement');
run('fullRestart();state.turn=2;freezeIntent()');
assert.equal(run('state.omen.type'),'fracture');
const announced=run('JSON.stringify(state.omen)');
run('state.units.find(u=>u.id===1).x=4');
assert.equal(run('JSON.stringify(state.omen)'),announced,'omen does not retarget');
run('state.intent=[];resolveEnemy()');
assert.equal(run('state.rifts.some(r=>r.x===2&&r.y===5)'),true,'fracture creates preannounced rift');
run('fullRestart();state.turn=3;freezeIntent()');
assert.equal(run('state.omen.type'),'surge');
const before=run('state.corruption');
run('state.intent=[];state.rifts=[];resolveEnemy()');
assert.equal(run('state.corruption'),before+6,'surge increases corruption');
run('campaign.sector=1;init()');
assert.equal(run("alive('enemy').some(e=>e.type==='weaver')"),true);
assert.equal(run("state.intent.some(i=>i.attack==='web')"),true);
run('campaign.sector=2;init()');
assert.equal(run("alive('enemy').some(e=>e.type==='seer')"),true);
assert.equal(run("state.intent.some(i=>i.attack==='vision')"),true);
assert.equal(run("state.intent.every(i=>inside(i.x,i.y))"),true);
run('persist()');assert.ok(saved.has('into-the-abyss.v0.8.save'));
// Upgrade from v0.7 if v0.8 doesn't exist in the local store.
saved.delete('into-the-abyss.v0.8.save');
const prior=JSON.parse(run('JSON.stringify({version:7,campaign,state})'));
delete prior.state.omen;
saved.set('into-the-abyss.v0.7.save',JSON.stringify(prior));
assert.equal(run('restore()'),true,'legacy v0.7 save migrates');
assert.equal(run('state.omen'),null,'missing omen defaults safely');
console.log('PASS phase8: warnings locked, fracture/surge effects, Tejedor/Oráculo, save and legacy migration');
